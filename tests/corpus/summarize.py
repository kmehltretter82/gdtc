"""Summarize a corpus results.tsv as Markdown.

usage: summarize.py results.tsv TAG COMMIT DTC_VERSION FLAGS [BASELINE.tsv]

BASELINE.tsv, if given, is an earlier run's file/class/missing columns; its
ranking of missing features is shown next to the current one.
"""
import collections
import sys

path, tag, commit, dtc_version, flags = sys.argv[1:6]
baseline_path = sys.argv[6] if len(sys.argv) > 6 else None


def read(name):
    with open(name, encoding="utf-8", errors="replace") as f:
        header = f.readline().rstrip("\n").split("\t")
        return [dict(zip(header, line.rstrip("\n").split("\t"))) for line in f]


rows = read(path)

classes = collections.Counter(r["class"] for r in rows)
order = ["identical", "different", "unsupported", "gdtc-error", "gdtc-accepts",
         "both-reject", "cpp-error"]
meaning = {
    "identical": "dtc and gdtc both succeed; the blobs are byte-identical",
    "different": "both succeed; the blobs differ",
    "unsupported": "dtc succeeds; gdtc reports an unimplemented feature",
    "gdtc-error": "dtc succeeds; gdtc fails for another reason",
    "gdtc-accepts": "dtc fails; gdtc succeeds",
    "both-reject": "dtc and gdtc both fail",
    "cpp-error": "the C preprocessor fails; neither compiler runs",
}

out = []
w = out.append
w(f"# Linux {tag} corpus\n")
w(f"Every `arch/*/boot/dts/**/*.dts` of Linux {tag} (`{commit}`), preprocessed as")
w("the kernel's `scripts/Makefile.dtbs` does and compiled with upstream")
w(f"{dtc_version} and with gdtc using the same `-i` paths"
  + (f" and `{flags}`." if flags else ".") + " Generated by")
w("`tests/corpus/linux.sh`; the per-file comparison log, with the SHA-256 of")
w(f"both blobs, is [`tests/corpus/linux-{tag}.tsv`](../tests/corpus/linux-{tag}.tsv).\n")
w("## Summary\n")
w("| Result | Files | Meaning |")
w("|---|---:|---|")
for c in order:
    w(f"| {c} | {classes.get(c, 0)} | {meaning[c]} |")
for c in sorted(set(classes) - set(order)):
    w(f"| {c} | {classes[c]} | |")
w(f"| **total** | **{len(rows)}** | |\n")

def ranking(source, title, empty):
    need = [set(r["missing"].split(",")) for r in source if r["class"] == "unsupported"]
    w(f"## {title}\n")
    if not need:
        w(empty + "\n")
        return
    uses = collections.Counter(f for s in need for f in s)
    alone = collections.Counter(next(iter(s)) for s in need if len(s) == 1)
    w("Files are counted once per feature they need. *Unblocks* follows a greedy")
    w("implementation order: each row is the feature that, added to the rows above")
    w("it, lets the most remaining files compile.\n")
    w("| Order | Feature | Files needing it | Only missing feature | Unblocks | Cumulative |")
    w("|---:|---|---:|---:|---:|---:|")
    done = set()
    total = 0
    rank = 0
    while len(done) < len(uses):
        def gain(f):
            return sum(1 for s in need if s <= done | {f} and not s <= done)
        best = max(sorted(uses.keys() - done), key=lambda f: (gain(f), uses[f]))
        g = gain(best)
        done.add(best)
        total += g
        rank += 1
        w(f"| {rank} | `{best}` | {uses[best]} | {alone.get(best, 0)} | {g} | {total} |")
    w("")


ranking(rows, "Missing features", "No file needs an unimplemented feature.")
if baseline_path:
    ranking(read(baseline_path), "Missing features at the baseline",
            "The baseline needed no unimplemented feature.")
    w(f"The baseline is [`tests/corpus/linux-{tag}-baseline.tsv`]"
      f"(../tests/corpus/linux-{tag}-baseline.tsv), the first run of the harness,")
    w("before any of these features was implemented. They were then implemented")
    w("in this order; see [`verification.md`](verification.md) for the progression.\n")

def listing(cls, title, limit=200):
    sel = [r for r in rows if r["class"] == cls]
    if not sel:
        return
    w(f"## {title}\n")
    w("| File | Detail |")
    w("|---|---|")
    for r in sel[:limit]:
        detail = r["detail"].replace("|", "\\|")
        w(f"| `{r['file']}` | {detail} |")
    if len(sel) > limit:
        w(f"| … | {len(sel) - limit} more in the TSV |")
    w("")

listing("different", "Different blobs")
listing("gdtc-error", "Other gdtc failures")
listing("gdtc-accepts", "Accepted by gdtc, rejected by dtc")
listing("both-reject", "Rejected by both")
listing("cpp-error", "Preprocessor failures")
print("\n".join(out))
